function numberWords(v) {
  const n = Math.round(num(v));
  if (!isFinite(n)) return '';
  const ones = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
  const tens = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
  const two = x => x < 20 ? ones[x] : tens[Math.floor(x / 10)] + (x % 10 ? ' ' + ones[x % 10] : '');
  const three = x => `${two(Math.floor(x / 100))} Hundred${x % 100 ? ' ' + two(x % 100) : ''}`;
  const chunk = (n, scale) => {
    if (n === 0) return '';
    const s = String(n).padStart(3, '0');
    const parts = [];
    const h = Number(s[0]), t = Number(s.slice(1));
    if (h) parts.push(ones[h] + ' Hundred');
    if (t) parts.push(two(t));
    return parts.join(' ') + (scale ? ' ' + scale : '');
  };
  if (n === 0) return 'Zero';
  const scales = [[1e9, 'Billion'], [1e6, 'Million'], [1e3, 'Thousand'], [1, '']];
  let out = [], rem = n;
  for (const [val, name] of scales) {
    const c = Math.floor(rem / val);
    if (c > 0) { out.push(chunk(c, name)); rem %= val; }
  }
  return out.join(' ').trim() + ' ' + CURRENCY() + ' only';
}

