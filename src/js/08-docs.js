const Docs = {};

/** Documents accept either a record id or the record itself. */
function docRecord(col, input, keys) {
  if (!input) return null;
  if (typeof input === 'object') return input;
  const ks = keys || ['id'];
  return DB.get(col).find(r => ks.some(k => r[k] === input)) || null;
}

function companyHeader(title, sub, metaLines) {
  const s = state.db.settings;
  return `<div class="doc-head">
    <div class="co">
      <img class="doc-logo" src="${BRAND.logo}" alt="${esc(BRAND.legalName)}">
      <h1>${esc(s.company || APP.name)}</h1>
      <div>${esc(s.address || '')}</div>
      <div>${esc(s.phone || '')} ${s.email ? ' · ' + esc(s.email) : ''}</div>
      ${s.taxNo ? `<div>Tax / Trade licence: ${esc(s.taxNo)}</div>` : ''}
    </div>
    <div class="meta">
      ${(metaLines || []).map(l => `<div>${l}</div>`).join('')}
    </div>
  </div>
  <div class="doc-title">${esc(title)}</div>
  ${sub ? `<div style="text-align:center;font-size:11px;color:#555;margin:-10px 0 14px">${sub}</div>` : ''}`;
}
function docSigs(blocks) {
  return `<div class="doc-sigs">${blocks.map(b => `<div class="doc-sig"><b>${esc(b.title)}</b>${b.lines.map(l => `<div>${l}</div>`).join('')}</div>`).join('')}</div>`;
}
function docFooter(note) {
  return `<div class="doc-foot">${esc(note || state.db.settings.footerNote || '')}<br>Generated by ${esc(APP.name)} v${APP.version} on ${esc(fmtDateTime(nowISO()))}</div>`;
}
function openDocument(html, title) {
  openModal({
    width: 'xl', autofocus: false,
    title: title || 'Document preview',
    sub: 'A4 · use “Print” for a paper copy or “Save as PDF” in the print dialog.',
    body: `<div class="doc" id="printDoc">${html}</div>`,
    foot: `<button class="btn" data-cancel>Close</button><button class="btn primary" data-print>🖨 Print / Save PDF</button>`,
    onMount(el) {
      qs('[data-print]', el).onclick = () => printDocument();
    }
  });
}
function printDocument() {
  $$('.page').forEach(p => p.classList.remove('print-active'));
  const doc = $('printDoc');
  if (!doc) return;
  /* Clone into a print root so @media print rules apply cleanly */
  let root = $('printRoot');
  if (!root) { root = document.createElement('div'); root.id = 'printRoot'; root.className = 'print-root'; document.body.appendChild(root); }
  root.innerHTML = doc.outerHTML;
  root.style.cssText = 'position:fixed;left:-10000px;top:0;width:820px;background:#fff;';
  setTimeout(() => {
    window.print();
    setTimeout(() => { root.innerHTML = ''; root.style.cssText = ''; }, 800);
  }, 120);
}

